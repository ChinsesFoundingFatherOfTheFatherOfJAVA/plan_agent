-- 004_drop_legacy_uk_center_time.sql
-- 目的：移除遗留全局唯一索引 uk_center_time，消除技术债 TD-001
--
-- 背景：
--   001 中该索引的注释已自述其局限：
--       「仅防完全重复的时间段分配；无法防止重叠（技术债务 TD-001）」
--   它是在缺少排他约束能力时的临时兜底。现状下它有两个问题：
--     1. 功能被 003 的 excl_center_time_overlap_in_plan 完全覆盖
--        （能防重叠，自然也能防完全重复）
--     2. 索引键为 (center_id, start_time, end_time) 且全局唯一，
--        不含 plan_id，导致两个候选方案在同一中心排出相同时间段时误报冲突，
--        直接抵消 003 「多计划并存」的设计目标
--
-- 结论：删除该索引，TD-001 关闭。
--   「同计划内不重叠」由 excl_center_time_overlap_in_plan 保证；
--   「同一时刻仅一版生效」由 production_plan.uk_plan_active 保证。
--
-- 保留 idx_task_time 作为普通查询索引（非唯一），不影响写入。
-- ============================================================

DROP INDEX IF EXISTS uk_center_time;